// The colour version of a 1-bit image, or nullptr to keep drawing the original.
static inline const RGB565Image *findRGB565Image(const uint8_t *xbm, int16_t w, int16_t h)
{
    for (const RGB565Image *img = rgb565Images; img->original; img++) {
        if (img->originalWidth == w && img->originalHeight == h &&
            (img->original == xbm || memcmp(img->original, xbm, ((w + 7) / 8) * h) == 0))
            return img;
    }
    return nullptr;
}
